"""Deterministic AtliQ Tees data: every brand × color × size, fixed prices and stock.

The original MySQL script filled the table with RAND(), so every install had different
numbers and the few-shot answers were meaningless. Here the same seed always produces the
same 80 t-shirts and 10 discounts, written either to SQLite (default) or as a MySQL script.

    python -m tshirt_agent.seed_data              # build data/atliq_tshirts.db
    python -m tshirt_agent.seed_data --mysql-sql  # rewrite database/db_creation_atliq_t_shirts.sql
"""

from __future__ import annotations

import argparse
import itertools
import random
import sqlite3
from pathlib import Path

from tshirt_agent.config import DEFAULT_SQLITE_PATH, PROJECT_ROOT

BRANDS = ("Van Heusen", "Levi", "Nike", "Adidas")
COLORS = ("Red", "Blue", "Black", "White")
SIZES = ("XS", "S", "M", "L", "XL")
SEED = 42
# (t_shirt_id, pct_discount): the same ten discounts as the original script
DISCOUNTS = [
    (1, 10.0),
    (2, 15.0),
    (3, 20.0),
    (4, 5.0),
    (5, 25.0),
    (6, 10.0),
    (7, 30.0),
    (8, 35.0),
    (9, 40.0),
    (10, 45.0),
]

MYSQL_SCRIPT = PROJECT_ROOT / "database" / "db_creation_atliq_t_shirts.sql"


def t_shirt_rows(seed: int = SEED) -> list[tuple[int, str, str, str, int, int]]:
    """(t_shirt_id, brand, color, size, price, stock_quantity) for all 80 combinations."""
    rng = random.Random(seed)
    rows = []
    for number, (brand, color, size) in enumerate(itertools.product(BRANDS, COLORS, SIZES), start=1):
        rows.append((number, brand, color, size, rng.randint(10, 50), rng.randint(10, 100)))
    return rows


SQLITE_SCHEMA = """
CREATE TABLE t_shirts (
    t_shirt_id INTEGER PRIMARY KEY,
    brand TEXT NOT NULL CHECK (brand IN ('Van Heusen', 'Levi', 'Nike', 'Adidas')),
    color TEXT NOT NULL CHECK (color IN ('Red', 'Blue', 'Black', 'White')),
    size TEXT NOT NULL CHECK (size IN ('XS', 'S', 'M', 'L', 'XL')),
    price INTEGER NOT NULL CHECK (price BETWEEN 10 AND 50),
    stock_quantity INTEGER NOT NULL,
    UNIQUE (brand, color, size)
);
CREATE TABLE discounts (
    discount_id INTEGER PRIMARY KEY,
    t_shirt_id INTEGER NOT NULL REFERENCES t_shirts(t_shirt_id),
    pct_discount REAL NOT NULL CHECK (pct_discount BETWEEN 0 AND 100)
);
"""


def build_sqlite(path: Path = DEFAULT_SQLITE_PATH) -> Path:
    """(Re)create the SQLite database file atomically and return its path."""
    path.parent.mkdir(parents=True, exist_ok=True)
    staging = path.with_suffix(".tmp")
    staging.unlink(missing_ok=True)
    with sqlite3.connect(staging) as connection:
        connection.executescript(SQLITE_SCHEMA)
        connection.executemany("INSERT INTO t_shirts VALUES (?, ?, ?, ?, ?, ?)", t_shirt_rows())
        connection.executemany("INSERT INTO discounts (t_shirt_id, pct_discount) VALUES (?, ?)", DISCOUNTS)
    connection.close()
    staging.replace(path)
    return path


def mysql_script() -> str:
    """The same data as a MySQL script (CREATE DATABASE, tables, fixed INSERTs)."""
    values = ",\n".join(
        f"({i}, '{brand}', '{color}', '{size}', {price}, {stock})"
        for i, brand, color, size, price, stock in t_shirt_rows()
    )
    discounts = ",\n".join(f"({t_shirt_id}, {pct:.2f})" for t_shirt_id, pct in DISCOUNTS)
    return f"""-- AtliQ Tees database for MySQL (generated by: python -m tshirt_agent.seed_data --mysql-sql)
-- Deterministic data: the same 80 t-shirts and 10 discounts as the default SQLite database.
CREATE DATABASE IF NOT EXISTS atliq_tshirts;
USE atliq_tshirts;

DROP TABLE IF EXISTS discounts;
DROP TABLE IF EXISTS t_shirts;

CREATE TABLE t_shirts (
    t_shirt_id INT PRIMARY KEY,
    brand ENUM('Van Heusen', 'Levi', 'Nike', 'Adidas') NOT NULL,
    color ENUM('Red', 'Blue', 'Black', 'White') NOT NULL,
    size ENUM('XS', 'S', 'M', 'L', 'XL') NOT NULL,
    price INT NOT NULL CHECK (price BETWEEN 10 AND 50),
    stock_quantity INT NOT NULL,
    UNIQUE KEY brand_color_size (brand, color, size)
);

CREATE TABLE discounts (
    discount_id INT AUTO_INCREMENT PRIMARY KEY,
    t_shirt_id INT NOT NULL,
    pct_discount DECIMAL(5,2) NOT NULL CHECK (pct_discount BETWEEN 0 AND 100),
    FOREIGN KEY (t_shirt_id) REFERENCES t_shirts(t_shirt_id)
);

INSERT INTO t_shirts (t_shirt_id, brand, color, size, price, stock_quantity) VALUES
{values};

INSERT INTO discounts (t_shirt_id, pct_discount) VALUES
{discounts};

-- A read-only user for the app (change the password):
-- CREATE USER 'atliq_reader'@'localhost' IDENTIFIED BY 'change_me';
-- GRANT SELECT ON atliq_tshirts.* TO 'atliq_reader'@'localhost';
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--mysql-sql", action="store_true", help="write the MySQL script instead")
    args = parser.parse_args()
    if args.mysql_sql:
        MYSQL_SCRIPT.write_text(mysql_script(), encoding="utf-8")
        print(f"Wrote {MYSQL_SCRIPT.relative_to(PROJECT_ROOT)}")
    else:
        path = build_sqlite()
        print(f"Built {path.relative_to(PROJECT_ROOT)}: {len(t_shirt_rows())} t-shirts, {len(DISCOUNTS)} discounts")


if __name__ == "__main__":
    main()
